import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

try {
	const short = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
	const content = `// AUTO-GENERATED by scripts/generate-commit.ts — do not edit manually
export const COMMIT: string | undefined = '${short}';
`;
	writeFileSync(join(root, 'src/lib/commit.ts'), content, 'utf8');
} catch {
	const content = `// AUTO-GENERATED by scripts/generate-commit.ts — do not edit manually
export const COMMIT: string | undefined = undefined;
`;
	writeFileSync(join(root, 'src/lib/commit.ts'), content, 'utf8');
}
